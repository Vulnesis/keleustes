/// Adds the icon font as a fallback to both text families, so icon
/// codepoints render inline with any label.
pub fn install(ctx: &egui::Context) {
    let mut fonts = egui::FontDefinitions::default();
    fonts.font_data.insert(
        "phosphor".into(),
        std::sync::Arc::new(egui::FontData::from_static(FONT)),
    );
    for family in [egui::FontFamily::Proportional, egui::FontFamily::Monospace] {
        fonts
            .families
            .entry(family)
            .or_default()
            .push("phosphor".into());
    }
    ctx.set_fonts(fonts);
}

/// "icon  label" for buttons, tabs and headings.
pub fn label(icon: &str, text: &str) -> String {
    format!("{icon}  {text}")
}
